package com.example.ck_mobile.model;

import com.google.firebase.firestore.DocumentId;

public class UserProfile {
    @DocumentId
    private String uid;
    private String kycStatus; // NONE / PENDING / APPROVED / REJECTED
    private String fullName;
    private String email;
    private String phone;
    private String address;
    private String accountNumber;
    private String role;   // "CUSTOMER" hoặc "OFFICER"
    private String status; // "ACTIVE" hoặc "LOCKED"

    public UserProfile() {
        // Bắt buộc có constructor rỗng cho Firestore
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getAccountNumber() {
        return accountNumber;
    }

    public void setAccountNumber(String accountNumber) {
        this.accountNumber = accountNumber;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getUid() {
        return uid;
    }

    public void setUid(String uid) {
        this.uid = uid;
    }

    public String getKycStatus() {
        return kycStatus;
    }

    public void setKycStatus(String kycStatus) {
        this.kycStatus = kycStatus;
    }
}
